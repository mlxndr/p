/* head.js — the shared <head> for every deck, written synchronously.

   Loaded as a plain blocking <script> in each deck's <head>, so the
   stylesheets (and the right theme) are in place before the first paint:
   no flash of a default theme, and no race with the scripts that follow.

   It also owns the theme catalogue (the menu in revconfig.js reads
   window.MGA_THEMES) and decides which theme a deck opens in:

     1. ?theme=slate in the URL           (this visit only, never saved)
     2. the visitor's saved choice         (script-loader.js saves menu picks)
     3. "theme": "burgundy" in meta.json   (a deck's own default, optional;
                                            <html data-theme> also works)
     4. DEFAULT_THEME below                (Terracotta)

   "lockTheme": true in meta.json skips step 2: the deck always opens in
   its own theme, whatever the visitor chose elsewhere (High Accessibility
   included). A visitor can still pick another theme from the menu for
   that visit; script-loader.js does not save it. "pdfTheme" replaces the
   deck's theme in export (?fragments=false or ?print-pdf), unless the
   URL names a theme.

   Forms (the "Forms" section) are themes that take their colours from a
   palette (inc/css/palettes.css): html.pal-NAME plus html.pal-light or
   html.pal-dark. The palette is chosen in this order:

     1. ?palette=petrol in the URL         (this visit only)
     2. the visitor's choice for this deck (the menu's swatches; saved per deck)
     3. "palette": "petrol" in meta.json   (the deck's own; "pdfPalette" in export)
     4. the form's default palette

   Theme keys are the short names in the catalogue. Filenames stay fixed
   because saved choices in visitors' browsers point at them; a saved
   theme that is no longer in the catalogue is forgotten. */
(function () {
    'use strict';

    /* The site root, relative to the deck: '../' for a deck one folder
       down (specimen/), '../../' for one two down (research/icame47/, 1a/7/), '../../../'
       for one three down (2a/words/2/). Taken from the
       path the deck's own index.html gives for this file. */
    var me = document.currentScript && document.currentScript.getAttribute('src');
    var ROOT = (me && /inc\/head\.js/.test(me)) ? me.replace(/inc\/head\.js.*$/, '') : '../';
    window.MGA_ROOT = ROOT;
    var CSS = ROOT + 'inc/css/';
    var DEFAULT_THEME = 'terracotta';

    /* Theme catalogue, grouped into menu sections. Headers in the menu are
       generated from this, so entries can be added or reordered freely. */
    var THEMES = [
        { name: 'Forms', themes: [
            { key: 'plate',       name: 'Plate and Key',  file: 'form-plate.css',       form: true, palette: 'silver-navy',   dark: 'navy-gold' },
            { key: 'fair-copy',   name: 'Fair Copy',      file: 'form-fair-copy.css',   form: true, palette: 'slate',         dark: 'charcoal-coral' },
            { key: 'attested',    name: 'Attested Forms', file: 'form-attested.css',    form: true, palette: 'silver-claret', dark: 'navy-gold' },
            { key: 'thumb',       name: 'Thumb Index',    file: 'form-thumb.css',       form: true, palette: 'petrol',        dark: 'claret-gold' },
            { key: 'thumb-quiet', name: 'Quiet Index',    file: 'form-thumb-quiet.css', form: true, palette: 'cream-oxblood', dark: 'charcoal-brass' },
            { key: 'lantern',     name: 'Lantern Slide',  file: 'form-lantern.css',     form: true, palette: 'silver-lamp',   dark: 'claret-gold' }
        ]},
        { name: 'Colourful', themes: [
            { key: 'terracotta', name: 'Terracotta', file: 'th-l-terracotta.css' },
            { key: 'burgundy',   name: 'Burgundy',   file: 'th-l-burgundy.css' },
            { key: 'slate',      name: 'Slate',      file: 'th-l-slate.css' },
            { key: 'petrol',     name: 'Petrol',     file: 'th-l-petrol.css' }
        ]},
        { name: 'Classic', themes: [
            { key: 'cream',      name: 'Cream',      file: 'th-l-cr.css' },
            { key: 'cream-sans', name: 'Cream Sans', file: 'th-l-cr-m-thin.css' },
            { key: 'cream-serif', name: 'Cream Serif', file: 'th-l-cr-serif.css' },
            { key: 'manuscript', name: 'Manuscript', file: 'th-l-e-cr-invert.css' },
            { key: 'twilight',   name: 'Twilight',   file: 'th-d-bg-twilight.css' },
            { key: 'charcoal',   name: 'Charcoal',   file: 'th-d-charcoal.css' }
        ]},
        { name: 'Other', themes: [
            { key: 'accessible',    name: 'High Accessibility', file: 'th-l-acc.css' }
        ]},
        { name: 'Institutional', themes: [
            { key: 'uog',      name: 'University of Glasgow',      file: 'th-l-uog.css' },
            { key: 'ht',       name: 'Historical Thesaurus',       file: 'th-l-ht.css' },
            { key: 'ht-cream', name: 'Historical Thesaurus Cream', file: 'th-l-bg-ht-cr.css' }
        ]}
    ];

    /* Palettes for the forms (inc/css/palettes.css, generated by
       scripts/build-palettes.py); paper and accent draw the menu swatches */
    var PALETTES = [
        { key: 'silver-navy', name: 'Silver and navy', mode: 'light', paper: '#F3F5F8', accent: '#13243E' },
        { key: 'silver-claret', name: 'Silver and claret', mode: 'light', paper: '#F3F5F8', accent: '#8C2A3C' },
        { key: 'burgundy', name: 'Burgundy', mode: 'light', paper: '#FAF5F0', accent: '#6A1D30' },
        { key: 'slate', name: 'Slate', mode: 'light', paper: '#F6F8FA', accent: '#385174' },
        { key: 'cream-oxblood', name: 'Cream and oxblood', mode: 'light', paper: '#F5F2EA', accent: '#7D2E28' },
        { key: 'petrol', name: 'Petrol', mode: 'light', paper: '#F5F9F8', accent: '#264D51' },
        { key: 'terracotta', name: 'Terracotta', mode: 'light', paper: '#F8F1E9', accent: '#A8432A' },
        { key: 'silver-lamp', name: 'Silver and lamp', mode: 'light', paper: '#F3F5F8', accent: '#E8A630' },
        { key: 'navy-gold', name: 'Navy and gold', mode: 'dark', paper: '#16202E', accent: '#D9B95B' },
        { key: 'charcoal-brass', name: 'Charcoal and brass', mode: 'dark', paper: '#1F2326', accent: '#C8A464' },
        { key: 'charcoal-coral', name: 'Charcoal and coral', mode: 'dark', paper: '#222021', accent: '#F2706F' },
        { key: 'plum-rose', name: 'Plum and rose', mode: 'dark', paper: '#2A2230', accent: '#D8B4C9' },
        { key: 'claret-gold', name: 'Claret and gold', mode: 'dark', paper: '#3A0F1D', accent: '#E8B64A' },
        { key: 'slate-silver', name: 'Slate and silver', mode: 'dark', paper: '#20252F', accent: '#A3BEDC' }
    ];
    function palByKey(k) {
        k = (k || '').toLowerCase();
        for (var i = 0; i < PALETTES.length; i++) if (PALETTES[i].key === k) return PALETTES[i];
        return null;
    }

    var all = [];
    THEMES.forEach(function (s) {
        s.themes.forEach(function (t) { t.href = CSS + t.file; all.push(t); });
    });
    function byKey(k) {
        k = (k || '').toLowerCase();
        for (var i = 0; i < all.length; i++) if (all[i].key === k) return all[i];
        return null;
    }
    /* by filename, so a choice saved in a deck at one depth is found
       from a deck at another */
    function byHref(h) {
        var f = (h || '').replace(/^.*\/inc\/css\//, '');
        for (var i = 0; i < all.length; i++) if (all[i].file === f) return all[i];
        return null;
    }

    /* Decide the opening theme */
    var fromUrl = null, saved = null;
    try { fromUrl = byKey(new URLSearchParams(location.search).get('theme')); } catch (e) {}
    try {
        var s = localStorage.getItem('theme');
        if (s) {
            saved = byHref(s);
            if (!saved) localStorage.removeItem('theme');   // retired theme
        }
    } catch (e) {}
    /* The deck's own defaults, from "theme"/"palette" in its meta.json.
       Read synchronously (a tiny local file) because the theme must be
       known before the page is first drawn; browsers log a deprecation
       note about synchronous requests, which is harmless here. */
    var meta = {};
    try {
        var x = new XMLHttpRequest();
        x.open('GET', './meta.json', false);
        x.send(null);
        if ((x.status >= 200 && x.status < 300) || (x.status === 0 && x.responseText)) {
            meta = JSON.parse(x.responseText) || {};
        }
    } catch (e) {}
    var deck = byKey(meta.theme) || byKey(document.documentElement.getAttribute('data-theme'));
    var locked = meta.lockTheme === true && !!deck;
    var exporting = /[?&](fragments=false|print-pdf)\b/.test(location.search);
    var forPdf = exporting ? byKey(meta.pdfTheme) : null;
    var chosen = fromUrl || forPdf || (locked ? deck : saved || deck) || byKey(DEFAULT_THEME);
    if (meta.lockTheme === true && !deck) {
        console.warn('[theme] "lockTheme" needs a "theme" in meta.json to lock to');
    }

    /* Corporate mode (SPEC 8): "corporate": "uog", or the settings object
       { "template": "uog", "body": "textbox"|"placeholder", "text": 24,
       "cards": "session"|"boards"|"template", "cardColours": [...] }.
       The deck is locked to the corporate stylesheet: no theme or palette
       choice, no saved or URL override, export included. */
    var CORP = { uog: 'corp-uog.css' };
    var corpIn = meta.corporate;
    var corp = null;
    if (corpIn) {
        corp = typeof corpIn === 'string' ? { template: corpIn } : corpIn;
        if (!CORP[corp.template]) {
            console.warn('[corporate] unknown template "' + corp.template + '"; using uog');
            corp.template = 'uog';
        }
        corp.body = corp.body === 'placeholder' ? 'placeholder' : 'textbox';
        if (['session', 'boards', 'template'].indexOf(corp.cards || 'session') === -1) {
            console.warn('[corporate] "cards" is session, boards or template, not "' + corp.cards + '"');
            corp.cards = 'session';
        }
        corp.cards = corp.cards || 'session';
        chosen = { key: 'corp-' + corp.template, href: CSS + CORP[corp.template] };
        var rc = document.documentElement.classList;
        rc.add('corp', 'corp-' + corp.template, 'corp-cards-' + corp.cards, 'corp-body-' + corp.body);
        if (corp.text) document.documentElement.style.setProperty('--corp-text', (2 * parseFloat(corp.text)) + 'px');
        locked = true;
    }
    window.MGA_CORPORATE = corp;

    window.MGA_META = meta;
    window.MGA_THEME_LOCKED = locked;
    window.MGA_THEMES = THEMES;
    /* Builds appear with a fade (teaching) or instantly ("buildStyle":
       "appear"; the corporate default) */
    var buildStyle = meta.buildStyle || (meta.corporate ? 'appear' : 'fade');
    if (buildStyle === 'appear') document.documentElement.classList.add('mga-build-appear');
    else if (buildStyle !== 'fade') console.warn('[meta] "buildStyle" is "fade" or "appear", not "' + buildStyle + '"');
    /* Palette (forms only). The deck's saved choice is kept per deck, so
       each lecture of a series can keep its own colours. */
    var DECK = location.pathname.replace(/[^\/]*$/, '');
    var palUrl = null, palSaved = null;
    try { palUrl = palByKey(new URLSearchParams(location.search).get('palette')); } catch (e) {}
    try { palSaved = palByKey(localStorage.getItem('palette:' + DECK)); } catch (e) {}
    function paletteFor(theme) {
        if (!theme || !theme.form) return null;
        return palUrl || (exporting ? palByKey(meta.pdfPalette) : null) ||
            palSaved || palByKey(meta.palette) || palByKey(theme.palette);
    }
    function applyPalette(p) {
        var c = document.documentElement.classList;
        Array.prototype.slice.call(c).forEach(function (n) {
            if (/^pal-/.test(n) || n === 'mga-form') c.remove(n);
        });
        if (p) c.add('mga-form', 'pal-' + p.key, 'pal-' + p.mode);
        window.MGA_PALETTE = p ? p.key : null;
    }
    /* Form options from meta.json ("formOptions": ["graphite"]) become
       classes on <html> (form-opt-graphite) that a form may style */
    (Array.isArray(meta.formOptions) ? meta.formOptions : []).forEach(function (o) {
        if (/^[a-z0-9-]+$/.test(o)) document.documentElement.classList.add('form-opt-' + o);
    });
    if (meta.palette && !palByKey(meta.palette)) console.warn('[palette] unknown palette "' + meta.palette + '"');
    applyPalette(corp ? null : paletteFor(chosen));
    window.MGA_PALETTES = PALETTES;
    /* The menu: a theme change (forms gain their palette, others lose it)
       and a palette pick (saved for this deck unless the URL named one) */
    window.mgaThemeChanged = function (href) {
        var t = byHref(href) || null;
        applyPalette(paletteFor(t));
        return t;
    };
    window.mgaSetPalette = function (key) {
        var p = palByKey(key);
        if (!p) return;
        palSaved = p; palUrl = null;
        try { localStorage.setItem('palette:' + DECK, p.key); } catch (e) {}
        applyPalette(p);
    };
    window.mgaFormByHref = function (href) { var t = byHref(href); return t && t.form ? t : null; };
    window.MGA_THEME_FROM_URL = !!fromUrl;

    /* Export (SPEC 10). ?export opens the export page in place of the
       slides (inc/export.js). The print views it opens are reveal's print
       mode (?print-pdf) with these options:
         fragments=false   final state (reveal's own option)
         builds=1          one page per build
         handout=1|2|3|6|16 slides per A4 page, framed and numbered
                           (16: a landscape grid for the lectern)
         lines=1           lines for notes beside or beneath each slide
         student=1         leaves out @slide nohandout and hides answers
         spares=0          leaves out @slide spare slides
         paper=1           each slide on a sheet of the paper chosen in
                           the print dialogue (A4 or Letter, either way
                           round), scaled to its width and centred
       handout.html reads student and spares too, with the student
       version as its default.

       Safari (and every WebKit browser) prints only on the paper sizes
       its dialogue offers and ignores a page size set in CSS, so its
       slide views always take paper=1 (phase 8). */
    var q = null;
    try { q = new URLSearchParams(location.search); } catch (e) {}
    function opt(k, dflt) {
        if (!q || !q.has(k)) return dflt;
        return !/^(0|false|no|off)$/i.test(q.get(k));
    }
    var perPage = q ? parseInt(q.get('handout'), 10) : 0;
    var X = {
        page: !!(q && q.has('export')),
        print: !!(q && q.has('print-pdf')),
        final: !!(q && q.get('fragments') === 'false'),
        builds: opt('builds', false),
        handout: [1, 2, 3, 6, 16].indexOf(perPage) !== -1 ? perPage : 0,
        lines: opt('lines', false),
        student: opt('student', false),
        spares: opt('spares', true),
        paper: opt('paper', false)
    };
    if (q && q.has('handout') && !X.handout) console.warn('[export] handout= takes 1, 2, 3, 6 or 16 slides per page');
    if (!X.print) X.handout = 0;
    var ua = navigator.userAgent || '';
    var WEBKIT = /AppleWebKit\//.test(ua) && !/(Chrome|Chromium|Edg|OPR)\//.test(ua);
    window.MGA_WEBKIT = WEBKIT;
    if (X.print && WEBKIT) X.paper = true;
    if (!X.print || X.handout) X.paper = false;
    window.MGA_EXPORT = X;
    var rcx = document.documentElement.classList;
    if (WEBKIT) rcx.add('mga-webkit');
    if (X.paper) rcx.add('mga-paper');
    if (X.student) rcx.add('mga-student');
    if (X.handout) rcx.add('mga-handout', 'mga-handout-' + X.handout);
    if (X.handout && X.lines) rcx.add('mga-lines');
    if (X.page) rcx.add('mga-export-page');

    /* The head itself */
    var h = [
        '<meta name="viewport" content="width=device-width, initial-scale=1.0">',
        '<meta name="author" content="Marc Alexander">',
        '<link rel="stylesheet" href="' + ROOT + 'inc/reveal.js/dist/reveal.css">',
        '<link rel="stylesheet" href="' + CSS + 'fonts.css">',
        '<link rel="stylesheet" href="' + CSS + 'base.css">',
        '<link rel="stylesheet" href="' + CSS + 'animations.css">',
        '<link rel="stylesheet" href="' + ROOT + 'inc/reveal.js/plugin/highlight/monokai.css">',
        /* Noto Sans/Serif: glyph-coverage fallback only (IPA, non-Latin).
           Loaded without blocking the page, so a slow or absent network
           never holds up the slides. */
        '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>',
        '<link rel="stylesheet" media="print" onload="this.media=\'all\'" href="https://fonts.googleapis.com/css2?family=Noto+Sans:ital,wght@0,100..900;1,100..900&family=Noto+Serif:ital,wght@0,100..900;1,100..900&display=swap">',
        '<link rel="icon" type="image/png" href="' + ROOT + 'favicon-96x96.png" sizes="96x96">',
        '<link rel="icon" type="image/svg+xml" href="' + ROOT + 'favicon.svg">',
        '<link rel="shortcut icon" href="' + ROOT + 'favicon.ico">',
        '<link rel="apple-touch-icon" sizes="180x180" href="' + ROOT + 'apple-touch-icon.png">',
        '<meta name="apple-mobile-web-app-title" content="mga.is">',
        '<link rel="manifest" href="' + ROOT + 'site.webmanifest">',
        '<link rel="stylesheet" href="' + chosen.href + '" id="theme">'
    ];
    /* the export files carry a version in their address, so a browser
       holding an old copy (Safari kept an old export.css with a new
       export.js, phase 8) fetches the new one: change it with them */
    window.MGA_EXPORT_V = '?v=8b';
    if (X.page || X.print) h.push('<link rel="stylesheet" href="' + CSS + 'export.css' + window.MGA_EXPORT_V + '">');
    document.write(h.join('\n'));

    /* Offline copies (see /sw.js). Not on a local preview server, where a
       cache would only get in the way of editing. */
    var local = /^(localhost|127\.0\.0\.1|\[::1\]|)$/.test(location.hostname) ||
                location.protocol === 'file:';
    if ('serviceWorker' in navigator && !local) {
        window.addEventListener('load', function () {
            navigator.serviceWorker.register('/sw.js').catch(function (e) {
                console.warn('[offline] service worker not registered:', e);
            });
        });
    }
    window.MGA_LOCAL_PREVIEW = local;
    if (local) document.documentElement.classList.add('mga-preview');
})();
