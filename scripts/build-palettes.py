"""Writes inc/css/palettes.css from the palette table below (run by hand after
changing a palette: python3 scripts/build-palettes.py) and prints any contrast
pair that falls short. The forms (form-*.css) take every colour from these roles."""
import json, os
def h2r(h): h=h.lstrip('#'); return [int(h[i:i+2],16)/255 for i in (0,2,4)]
def r2h(c): return '#'+''.join(f'{round(max(0,min(1,x))*255):02X}' for x in c)
def mix(a,b,t): A,B=h2r(a),h2r(b); return r2h([A[i]*t+B[i]*(1-t) for i in range(3)])
def lum(h):
    c=[x/12.92 if x<=.04045 else ((x+.055)/1.055)**2.4 for x in h2r(h)]; return .2126*c[0]+.7152*c[1]+.0722*c[2]
def cr(a,b): la,lb=sorted([lum(a),lum(b)],reverse=True); return (la+.05)/(lb+.05)
